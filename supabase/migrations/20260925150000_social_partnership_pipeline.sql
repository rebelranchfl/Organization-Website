-- 6. Move existing draft messages into threads (first outbound message per prospect)
insert into public.social_outreach_messages (outreach_id, direction, channel, to_address, subject, body, status, suggested_by, created_at)
select o.id, 'Outbound',
       case when o.contact_method ilike '%facebook%' then 'Facebook message'
            when o.contact_method ilike '%phone%' then 'Phone call'
            when o.contact_method ilike '%form%' then 'Web form'
            else 'Email' end,
       o.contact_email, o.subject, o.message,
       case o.status when 'Needs Edit' then 'Needs Edit' when 'Rejected' then 'Rejected' when 'Approved' then 'Approved' when 'Sent' then 'Sent' else 'Suggested' end,
       'Claude (2026-08 outreach batch)', o.created_at
from public.social_outreach o
where o.message is not null
  and not exists (select 1 from public.social_outreach_messages m where m.outreach_id = o.id);

