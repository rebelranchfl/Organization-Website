-- 1. Pipeline statuses + prospect research fields
alter table public.social_outreach drop constraint if exists social_outreach_status_check;
alter table public.social_outreach add constraint social_outreach_status_check
  check (status in ('Prospect','Prospect Approved','Researched','Draft','Needs Edit','Approved','Sent',
                    'Replied','Follow-Up','In Conversation','Partner','Declined','Rejected','Archived'));

alter table public.social_outreach
  add column if not exists fit_reason text,
  add column if not exists fit_score integer check (fit_score is null or fit_score between 1 and 5),
  add column if not exists county text,
  add column if not exists sources text,
  add column if not exists found_by text,
  add column if not exists last_contact_at timestamptz,
  add column if not exists last_inbound_at timestamptz;

-- 2. Conversation thread per prospect
create table if not exists public.social_outreach_messages (
  id bigint generated by default as identity primary key,
  outreach_id bigint not null references public.social_outreach(id) on delete cascade,
  direction text not null default 'Outbound' check (direction in ('Outbound','Inbound')),
  channel text not null default 'Email'
    check (channel in ('Email','Facebook message','Phone call','Web form','In person','Text','Other')),
  from_address text,
  to_address text,
  subject text,
  body text,
  status text not null default 'Suggested'
    check (status in ('Suggested','Needs Edit','Approved','Sent','Received','Rejected','Logged')),
  suggested_by text,
  owner_comment text,
  approved_at timestamptz,
  sent_at timestamptz,
  received_at timestamptz,
  external_ref text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists social_outreach_messages_outreach_idx on public.social_outreach_messages(outreach_id, created_at);
create index if not exists social_outreach_messages_status_idx on public.social_outreach_messages(status);
create unique index if not exists social_outreach_messages_external_ref_uniq
  on public.social_outreach_messages(external_ref) where external_ref is not null;

drop trigger if exists social_outreach_messages_set_updated_at on public.social_outreach_messages;
create trigger social_outreach_messages_set_updated_at before update on public.social_outreach_messages
for each row execute function private.set_updated_at();

-- 3. Owner-editable settings
create table if not exists public.social_settings (
  key text primary key check (key ~ '^[a-z0-9_]+$'),
  value text,
  label text,
  description text,
  sort_order integer not null default 100,
  updated_at timestamptz not null default now()
);
drop trigger if exists social_settings_set_updated_at on public.social_settings;
create trigger social_settings_set_updated_at before update on public.social_settings
for each row execute function private.set_updated_at();

-- 4. Security: administrators only
do $$
declare t text;
begin
  foreach t in array array['social_outreach_messages','social_settings']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on table public.%I from anon', t);
    execute format('revoke all on table public.%I from authenticated', t);
    execute format('grant select, insert, update, delete on table public.%I to authenticated', t);
    execute format('drop policy if exists %I on public.%I', t || '_admin_all', t);
    execute format('create policy %I on public.%I for all to authenticated using ((select private.is_admin())) with check ((select private.is_admin()))', t || '_admin_all', t);
  end loop;
end $$;
grant usage, select on sequence public.social_outreach_messages_id_seq to authenticated;

